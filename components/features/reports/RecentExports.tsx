"use client";

import * as React from "react";
import { Download } from "lucide-react";
import { Badge } from "@/components/ui/Badge";
import { SectionHeader } from "@/components/common/PageHeader";
import type { ExportRecord } from "@/types/reports";

const statusConfig: Record<ExportRecord["status"], { label: string; tone: "success" | "warning" | "danger" }> = {
  ready: { label: "READY", tone: "success" },
  processing: { label: "Processing", tone: "warning" },
  failed: { label: "Failed", tone: "danger" },
};

export interface RecentExportsProps {
  exports: ExportRecord[];
  className?: string;
}

export function RecentExports({ exports, className }: RecentExportsProps) {
  return (
    <div className={className}>
      <SectionHeader title="Recent Generated Exports" />

      <div className="overflow-x-auto rounded-lg border border-border bg-surface">
        <table className="w-full text-sm">
          <thead>
            <tr className="border-b border-border bg-surface-muted text-left">
              <th className="px-4 py-3 text-[11px] font-semibold uppercase tracking-wider text-foreground-secondary">Export ID</th>
              <th className="px-4 py-3 text-[11px] font-semibold uppercase tracking-wider text-foreground-secondary">Report Filename</th>
              <th className="px-4 py-3 text-[11px] font-semibold uppercase tracking-wider text-foreground-secondary">Generated By</th>
              <th className="px-4 py-3 text-[11px] font-semibold uppercase tracking-wider text-foreground-secondary">Format / Filesize</th>
              <th className="px-4 py-3 text-[11px] font-semibold uppercase tracking-wider text-foreground-secondary">Download Status</th>
              <th className="px-4 py-3 text-[11px] font-semibold uppercase tracking-wider text-foreground-secondary text-right">Download</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-border">
            {exports.map((ex) => {
              const cfg = statusConfig[ex.status];
              return (
                <tr key={ex.id} className="hover:bg-row-highlight transition-colors">
                  <td className="px-4 py-3 font-mono text-xs font-medium text-secondary">{ex.id}</td>
                  <td className="px-4 py-3 text-foreground">{ex.filename}</td>
                  <td className="px-4 py-3 text-foreground-secondary">{ex.generatedBy}</td>
                  <td className="px-4 py-3 text-foreground-secondary">{ex.format} / {ex.fileSize}</td>
                  <td className="px-4 py-3">
                    <Badge tone={cfg.tone} variant="soft" size="sm">
                      {cfg.label}
                    </Badge>
                  </td>
                  <td className="px-4 py-3 text-right">
                    <button
                      type="button"
                      aria-label={`Download ${ex.filename}`}
                      className="inline-flex items-center gap-1 text-secondary hover:underline text-xs font-medium"
                    >
                      <Download className="h-3.5 w-3.5" />
                      Dl
                    </button>
                  </td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>
    </div>
  );
}
