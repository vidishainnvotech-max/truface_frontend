/** Detail panel data. Falls back to a generic template derived from the employee record. */
export function getEmployeeDetails(id: string): EmployeeDetails | undefined {
  const employee = getEmployeeById(id);
  if (!employee) return undefined;
  if (id === "TF-1001") return aaravDetails;

  const gate = `${employee.location === "pune-assembly" ? "Pune Assembly" : "Main"} Gate A`;
  const methodLabel = employee.method === "face" ? "face" : employee.method === "rfid" ? "rfid" : "fingerprint";
  return {
    todayVerification: {
      verified: employee.status === "active",
      checkIn: employee.lastAttendance.includes("Today") ? employee.lastAttendance.replace("Today, ", "") : "—",
      terminal: gate,
      method: methodLabel,
    },
    recentLogs: aaravDetails.recentLogs.slice(0, 5),
    monthStats: aaravDetails.monthStats,
    attendancePattern: aaravDetails.attendancePattern,
    punctuality: aaravDetails.punctuality,
    biometrics: {
      face: { ...aaravDetails.biometrics.face, enrolled: employee.biometrics.face },
      rfid: { ...aaravDetails.biometrics.rfid, assigned: employee.biometrics.rfid },
      fingerprints: {
        count: employee.biometrics.fingerprint ? 2 : 0,
        profiles: employee.biometrics.fingerprint ? aaravDetails.biometrics.fingerprints.profiles : [],
      },
    },
    securityScore: aaravDetails.securityScore,
    monthSummary: aaravDetails.monthSummary,
    monthLogs: aaravDetails.monthLogs,
    assignedLocations: [
      { name: employee.location === "pune-assembly" ? "Pune Assembly Line" : gate, type: "Primary", radius: "100m" },
    ],
    recentCheckIns: aaravDetails.recentCheckIns.slice(0, 3),
    geofenceAdherence: "100%",
    violations: 0,
    system: aaravDetails.system,
    events: aaravDetails.events.slice(0, 5),
  };
}
