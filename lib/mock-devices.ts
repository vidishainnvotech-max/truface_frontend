export function getDeviceDiagnostics(id: string): DeviceDiagnostics | undefined {
  const item = getDeviceListItem(id);
  if (!item) return undefined;

  const typeLabel =
    item.typeLabel === "face-rfid" ? "Face ID + RFID Reader" : item.typeLabel === "fingerprint" ? "Fingerprint Scanner" : "RFID Only Reader";

  return {
    verificationEvents: 342,
    pendingQueue: item.pendingQueue,
    failedIncidents: item.status === "offline" ? 3 : 0,
    uptime30d: item.status === "offline" ? 96.4 : 99.8,
    lastSynced: item.lastSync.includes("day") ? "2 days ago (Auto-refreshing)" : `${item.lastSync} (Auto-refreshing)`,
    firmwareVersion: "v2.4.1 (Stable)",
    deviceTypeLabel: typeLabel,
    assignedLocation: item.location === "Pune Assembly Line" ? "Pune Plant — Assembly Line 1" : item.location,
    online: item.status !== "offline",
    events: feedEvents,
  };
}

